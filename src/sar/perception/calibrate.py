"""Measure the detector: probability of detecting each object at each lateral range from the
track (the lateral range curve), per sensor and wind class, and the false alarm rate. The sweep
width W = integral of the curve over both sides is what the planner uses (IAMSAR); the simulator's
truth uses the whole curve. Writes config/sensor_calibration.yaml."""

from __future__ import annotations

import time
from typing import Any

import numpy as np
import yaml

from sar import conf
from sar.perception.detect import detect
from sar.perception.render import FRAME_PX, GSD_M, SWATH_M, Scene, render

OFFSETS_M = [0, 5, 10, 15, 20, 25, 30, 35, 40, 45, 50, 55]
WIND_OF_CLASS = {"calm": 2.5, "moderate": 6.0, "fresh": 9.5}
HIT_RADIUS_M = 2.0


def hit(scene: Scene, frames: int, rng: np.random.Generator) -> float:
    tx, ty = FRAME_PX / 2 + scene.offset_m / GSD_M, FRAME_PX / 2
    hits = 0
    for _ in range(frames):
        dets = detect(render(scene, rng), scene.sensor)
        if any((d.x_px - tx) ** 2 + (d.y_px - ty) ** 2 <= (HIT_RADIUS_M / GSD_M) ** 2 for d in dets):
            hits += 1
    return hits / frames


def false_alarms_per_km2(sensor: str, wind: float, frames: int, rng: np.random.Generator) -> float:
    count = 0
    for _ in range(frames):
        count += len(detect(render(Scene(sensor, "piw", wind, 0.0, present=False), rng), sensor))
    return count / (frames * (SWATH_M / 1000.0) ** 2)


def calibrate(frames: int = 40, seed: int = 20261028) -> dict[str, Any]:
    rng = np.random.default_rng(seed)
    objects = list(conf.read("objects")["objects"])
    out: dict[str, Any] = {
        "generated_by": "sar calibrate",
        "frames_per_point": frames,
        "seed": seed,
        "camera": {"swath_m": SWATH_M, "gsd_m": round(GSD_M, 4), "hit_radius_m": HIT_RADIUS_M},
        "offsets_m": OFFSETS_M,
        "sensors": {},
        "false_alarms_per_km2": {},
    }
    for sensor in ("eo", "thermal"):
        out["sensors"][sensor] = {}
        out["false_alarms_per_km2"][sensor] = {}
        for wclass, wind in WIND_OF_CLASS.items():
            table = {}
            for obj in objects:
                lrc = [round(hit(Scene(sensor, obj, wind, float(x)), frames, rng), 4) for x in OFFSETS_M]
                width = 2.0 * float(np.trapezoid(lrc, OFFSETS_M))
                table[obj] = {"lrc": lrc, "sweep_width_m": round(width, 2)}
            out["sensors"][sensor][wclass] = table
            out["false_alarms_per_km2"][sensor][wclass] = round(false_alarms_per_km2(sensor, wind, frames, rng), 2)
    return out


def main(frames: int = 40) -> None:
    t0 = time.time()
    result = calibrate(frames)
    result["seconds"] = None  # wall time is not reproducible; kept out of the file
    with open(conf.path("config", "sensor_calibration.yaml"), "w", encoding="utf-8") as f:
        f.write("# GENERATED by `sar calibrate` from the synthetic camera and the OpenCV detector. Do not edit.\n")
        yaml.safe_dump(result, f, sort_keys=False, width=200)
    print(f"calibrated in {time.time() - t0:.0f}s")
    for sensor, classes in result["sensors"].items():
        for wclass, table in classes.items():
            widths = ", ".join(f"{k} {v['sweep_width_m']:.0f} m" for k, v in table.items())
            print(
                f"  {sensor:8s} {wclass:9s} W: {widths}; false alarms/km2 {result['false_alarms_per_km2'][sensor][wclass]}"
            )
